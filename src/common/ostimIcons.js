/** Group Select options by category (sexual, symbols, …). */
export function ostimIconSelectOptions() {
  const by = new Map();
  for (const path of ostimIconPaths) {
    const rest = path.startsWith('OStim/') ? path.slice(6) : path;
    const cat = rest.split('/')[0] || 'other';
    if (!by.has(cat)) by.set(cat, []);
    by.get(cat).push({ value: path, label: rest });
  }
  return [...by.entries()]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([label, options]) => ({ label, options }));
}
